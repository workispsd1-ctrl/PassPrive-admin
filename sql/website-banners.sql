-- Storage buckets: one public bucket per website banner table, matching the
-- app banner buckets (HomeHeroOffers, DineinHomeBanners, StoresHomeBanners,
-- WellnessHomeBanners, TouristHomeBanners). Create via SQL or via the
-- Supabase dashboard (Storage > New bucket > Public bucket) — either works.
insert into storage.buckets (id, name, public)
values
  ('WebsiteHomeBanners', 'WebsiteHomeBanners', true),
  ('WebsiteDineinBanners', 'WebsiteDineinBanners', true),
  ('WebsiteStoreBanners', 'WebsiteStoreBanners', true),
  ('WebsiteWellnessBanners', 'WebsiteWellnessBanners', true),
  ('WebsiteTouristBanners', 'WebsiteTouristBanners', true)
on conflict (id) do nothing;

-- storage.objects RLS: a bucket's "public" flag only affects anonymous reads
-- via the public URL — every upload/replace/delete still goes through the
-- authenticated storage API and is subject to RLS on storage.objects, so
-- each bucket needs its own read/write policies here (same admin/superadmin
-- check used on the tables above).
drop policy if exists websitehomebanners_storage_read on storage.objects;
create policy websitehomebanners_storage_read on storage.objects for select
  using (bucket_id = 'WebsiteHomeBanners');
drop policy if exists websitehomebanners_storage_admin_write on storage.objects;
create policy websitehomebanners_storage_admin_write on storage.objects for insert to authenticated
  with check (bucket_id = 'WebsiteHomeBanners' and exists (select 1 from public.users u where u.id = auth.uid() and lower(coalesce(u.role, '')) in ('admin', 'superadmin')));
drop policy if exists websitehomebanners_storage_admin_update on storage.objects;
create policy websitehomebanners_storage_admin_update on storage.objects for update to authenticated
  using (bucket_id = 'WebsiteHomeBanners' and exists (select 1 from public.users u where u.id = auth.uid() and lower(coalesce(u.role, '')) in ('admin', 'superadmin')))
  with check (bucket_id = 'WebsiteHomeBanners' and exists (select 1 from public.users u where u.id = auth.uid() and lower(coalesce(u.role, '')) in ('admin', 'superadmin')));
drop policy if exists websitehomebanners_storage_admin_delete on storage.objects;
create policy websitehomebanners_storage_admin_delete on storage.objects for delete to authenticated
  using (bucket_id = 'WebsiteHomeBanners' and exists (select 1 from public.users u where u.id = auth.uid() and lower(coalesce(u.role, '')) in ('admin', 'superadmin')));

