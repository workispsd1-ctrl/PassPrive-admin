-- Website banner tables.
--
-- Website creatives use different dimensions than the app ones, so each
-- website screen gets its own table + storage bucket, mirroring the
-- existing app banner tables (homeherooffers, dineinhomebanners,
-- storeshomebanners, wellnesshomebanners, touristhomebanners) rather than
-- sharing rows with them. Column shape (names, order, nullability, defaults)
-- matches those tables exactly, verified against the live schema via
-- information_schema.columns, so the existing admin UI
-- (app/dashboard/offers) works against them unmodified.
--
-- Assumes public.set_updated_at() already exists (it is reused, not
-- redefined, by sql/service-categories.sql in this repo).

create table if not exists public.websitehomebanners (
  id bigint generated by default as identity primary key,
  title text null,
  type text not null,
  media_url text not null,
  thumbnail_url text null,
  cta_text text null,
  cta_link text null,
  priority integer null default 1,
  is_active boolean null default true,
  start_at timestamp with time zone null,
  end_at timestamp with time zone null,
  created_at timestamp with time zone null default now(),
  updated_at timestamp with time zone null default now(),
  action jsonb null
) tablespace pg_default;

